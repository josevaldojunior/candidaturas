-- Contas de usuário: cada candidatura e cada contato passam a ter dono.
-- Registros antigos ficam sem dono (usuario_id nulo) e são assumidos pela primeira conta criada.

CREATE TABLE usuario (
    id                         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome                       VARCHAR(120) NOT NULL,
    email                      VARCHAR(200) NOT NULL,
    senha_hash                 VARCHAR(100) NOT NULL,
    token_integracao_hash      VARCHAR(64),
    token_integracao_criado_em TIMESTAMP,
    sem_retorno_dias           INTEGER      NOT NULL DEFAULT 30,
    criado_em                  TIMESTAMP    NOT NULL,
    CONSTRAINT uk_usuario_email UNIQUE (email),
    CONSTRAINT uk_usuario_token_integracao UNIQUE (token_integracao_hash),
    CONSTRAINT ck_usuario_sem_retorno_dias CHECK (sem_retorno_dias BETWEEN 1 AND 365)
);

ALTER TABLE candidatura ADD COLUMN usuario_id BIGINT;
ALTER TABLE candidatura ADD CONSTRAINT fk_candidatura_usuario
    FOREIGN KEY (usuario_id) REFERENCES usuario (id) ON DELETE CASCADE;
CREATE INDEX ix_candidatura_usuario ON candidatura (usuario_id);

-- a chave externa (do agente) passa a ser única por usuário, não no sistema todo
ALTER TABLE candidatura DROP CONSTRAINT uk_candidatura_chave_externa;
CREATE UNIQUE INDEX uk_candidatura_usuario_chave_externa ON candidatura (usuario_id, chave_externa);

ALTER TABLE contato ADD COLUMN usuario_id BIGINT;
ALTER TABLE contato ADD CONSTRAINT fk_contato_usuario
    FOREIGN KEY (usuario_id) REFERENCES usuario (id) ON DELETE CASCADE;
CREATE INDEX ix_contato_usuario ON contato (usuario_id);

-- o prazo de "sem retorno" passou a ser por conta (usuario.sem_retorno_dias, padrão 30)
DROP TABLE configuracao;
