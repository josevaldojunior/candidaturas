CREATE TABLE plataforma (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 usuario_id BIGINT NOT NULL REFERENCES usuario(id) ON DELETE CASCADE,
 codigo VARCHAR(40) NOT NULL, nome VARCHAR(120) NOT NULL, nome_chave VARCHAR(120) NOT NULL,
 ordem INTEGER NOT NULL, ativa BOOLEAN NOT NULL DEFAULT TRUE,
 CONSTRAINT uk_plataforma_codigo UNIQUE (usuario_id,codigo),
 CONSTRAINT uk_plataforma_nome UNIQUE (usuario_id,nome_chave)
);
