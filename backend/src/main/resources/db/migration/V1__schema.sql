-- Esquema inicial. SQL compatível com PostgreSQL e H2 (MODE=PostgreSQL).

CREATE TABLE candidatura (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa             VARCHAR(200)  NOT NULL,
    cargo               VARCHAR(200)  NOT NULL,
    link_vaga           VARCHAR(1000),
    plataforma          VARCHAR(20),
    modalidade          VARCHAR(20),
    tipo_contrato       VARCHAR(20),
    faixa_salarial      VARCHAR(100),
    pretensao_salarial  VARCHAR(100),
    nota                INTEGER,
    data_candidatura    DATE,
    status              VARCHAR(30)   NOT NULL,
    prioridade          VARCHAR(10)   NOT NULL,
    curriculo_versao    VARCHAR(100),
    observacoes         VARCHAR(4000),
    origem              VARCHAR(20)   NOT NULL,
    chave_externa       VARCHAR(300),
    ultima_interacao_em TIMESTAMP,
    criado_em           TIMESTAMP     NOT NULL,
    atualizado_em       TIMESTAMP     NOT NULL,
    CONSTRAINT uk_candidatura_chave_externa UNIQUE (chave_externa),
    CONSTRAINT ck_candidatura_nota CHECK (nota IS NULL OR (nota BETWEEN 1 AND 10))
);

CREATE INDEX ix_candidatura_link_vaga ON candidatura (link_vaga);
CREATE INDEX ix_candidatura_status ON candidatura (status);
CREATE INDEX ix_candidatura_data ON candidatura (data_candidatura);

CREATE TABLE candidatura_stack (
    candidatura_id BIGINT      NOT NULL,
    tag            VARCHAR(60) NOT NULL,
    CONSTRAINT pk_candidatura_stack PRIMARY KEY (candidatura_id, tag),
    CONSTRAINT fk_stack_candidatura FOREIGN KEY (candidatura_id) REFERENCES candidatura (id) ON DELETE CASCADE
);

CREATE TABLE historico_status (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    candidatura_id  BIGINT      NOT NULL,
    status_anterior VARCHAR(30),
    status_novo     VARCHAR(30) NOT NULL,
    data            TIMESTAMP   NOT NULL,
    CONSTRAINT fk_historico_candidatura FOREIGN KEY (candidatura_id) REFERENCES candidatura (id) ON DELETE CASCADE
);

CREATE INDEX ix_historico_candidatura ON historico_status (candidatura_id);

CREATE TABLE interacao (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    candidatura_id      BIGINT        NOT NULL,
    data                TIMESTAMP     NOT NULL,
    tipo                VARCHAR(20)   NOT NULL,
    descricao           VARCHAR(4000),
    proximo_passo       VARCHAR(1000),
    data_follow_up      DATE,
    follow_up_concluido BOOLEAN       NOT NULL DEFAULT FALSE,
    CONSTRAINT fk_interacao_candidatura FOREIGN KEY (candidatura_id) REFERENCES candidatura (id) ON DELETE CASCADE
);

CREATE INDEX ix_interacao_candidatura ON interacao (candidatura_id);
CREATE INDEX ix_interacao_follow_up ON interacao (data_follow_up, follow_up_concluido);

CREATE TABLE contato (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome     VARCHAR(200) NOT NULL,
    cargo    VARCHAR(20)  NOT NULL,
    email    VARCHAR(200),
    linkedin VARCHAR(500),
    telefone VARCHAR(50),
    empresa  VARCHAR(200)
);

CREATE INDEX ix_contato_email ON contato (email);

CREATE TABLE candidatura_contato (
    candidatura_id BIGINT NOT NULL,
    contato_id     BIGINT NOT NULL,
    CONSTRAINT pk_candidatura_contato PRIMARY KEY (candidatura_id, contato_id),
    CONSTRAINT fk_cc_candidatura FOREIGN KEY (candidatura_id) REFERENCES candidatura (id) ON DELETE CASCADE,
    CONSTRAINT fk_cc_contato FOREIGN KEY (contato_id) REFERENCES contato (id) ON DELETE CASCADE
);

CREATE TABLE configuracao (
    chave VARCHAR(100) PRIMARY KEY,
    valor VARCHAR(500) NOT NULL
);

